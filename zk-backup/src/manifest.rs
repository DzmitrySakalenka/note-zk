//! Backup manifest serialization primitives.

use std::{
    fs,
    io::{self, Read, Write},
    path::{Path, PathBuf},
};

use chrono::{DateTime, Utc};
use data_encoding::HEXLOWER;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::{BackupError, BackupResult};

/// Current backup manifest schema version.
pub const MANIFEST_SCHEMA_VERSION: u32 = 1;

const HASH_BUFFER_BYTES: usize = 64 * 1024;

/// Operator-readable metadata for one completed backup run.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BackupManifest {
    /// Manifest schema version. Version `1` is the only supported version.
    pub schema_version: u32,
    /// Stable backup identifier generated by the service layer.
    pub backup_id: String,
    /// Backup creation timestamp.
    pub created_at: DateTime<Utc>,
    /// Summary of source data included in the archive.
    pub source_summary: BackupSourceSummary,
    /// Archive file metadata used for restore-time integrity checks.
    pub archive: BackupArchiveDescriptor,
    /// Encryption metadata needed to pick the matching restore key.
    pub encryption: BackupManifestEncryption,
}

/// Summary of source data included in one backup archive.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BackupSourceSummary {
    /// Source vault path at backup creation time.
    pub vault_path: PathBuf,
    /// Number of note records included.
    pub note_count: u32,
    /// Number of asset records included.
    pub asset_count: u32,
    /// Whether a server database snapshot was included.
    pub server_db_included: bool,
    /// Size of the included server database snapshot, when included.
    pub server_db_size_bytes: Option<u64>,
}

/// Archive file metadata recorded in a backup manifest.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BackupArchiveDescriptor {
    /// Archive basename stored next to the manifest.
    pub file_name: String,
    /// Archive size in bytes.
    pub size_bytes: u64,
    /// Lowercase `SHA-256(archive)` hex digest.
    pub sha256_hex: String,
}

/// Encryption metadata recorded in a backup manifest.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum BackupManifestEncryption {
    /// Archive is not encrypted.
    None,
    /// Archive is age-encrypted for the recorded recipient fingerprint.
    Age {
        /// Operator-facing recipient fingerprint.
        recipient_fingerprint: String,
    },
}

/// Returns the manifest basename for one backup id.
#[must_use]
pub fn manifest_file_name(backup_id: &str) -> String {
    format!("backup-{backup_id}.manifest.json")
}

/// Writes one manifest as pretty JSON using a same-directory atomic rename.
///
/// # Errors
///
/// Returns [`BackupError::Io`] when filesystem operations fail, or
/// [`BackupError::InvalidManifest`] if serialization unexpectedly fails.
pub fn write_manifest(path: &Path, manifest: &BackupManifest) -> BackupResult<()> {
    let parent_dir = path.parent().ok_or_else(|| {
        BackupError::Io(io::Error::new(
            io::ErrorKind::InvalidInput,
            "manifest path has no parent directory",
        ))
    })?;
    let temp_path = temp_manifest_path(path);
    let write_result = write_manifest_temp_file(&temp_path, manifest)
        .and_then(|()| fs::rename(&temp_path, path).map_err(BackupError::from))
        .and_then(|()| sync_directory(parent_dir));

    if write_result.is_err() {
        let _ = fs::remove_file(&temp_path);
    }

    write_result
}

/// Reads one manifest and rejects unsupported schema versions.
///
/// # Errors
///
/// Returns [`BackupError::Io`] when reading fails, or
/// [`BackupError::InvalidManifest`] when JSON is malformed or the schema
/// version is unsupported.
pub fn read_manifest(path: &Path) -> BackupResult<BackupManifest> {
    let raw_json = fs::read(path)?;
    let manifest: BackupManifest =
        serde_json::from_slice(&raw_json).map_err(|_error| BackupError::InvalidManifest)?;

    if manifest.schema_version != MANIFEST_SCHEMA_VERSION {
        return Err(BackupError::InvalidManifest);
    }

    Ok(manifest)
}

/// Reads every manifest file from a directory in deterministic path order.
///
/// # Errors
///
/// Returns [`BackupError::Io`] when the directory cannot be listed, or
/// [`BackupError::InvalidManifest`] when a readable manifest has invalid JSON
/// or an unsupported schema version.
pub fn list_manifests(dir: &Path) -> BackupResult<Vec<BackupManifest>> {
    let mut manifest_paths = Vec::new();
    for entry_result in fs::read_dir(dir)? {
        let entry = match entry_result {
            Ok(entry) => entry,
            Err(error) => {
                tracing::warn!(error = %error, "skipping unreadable manifest directory entry");
                continue;
            }
        };
        let path = entry.path();
        if is_manifest_path(&path) {
            manifest_paths.push(path);
        }
    }

    manifest_paths.sort();

    let mut manifests = Vec::with_capacity(manifest_paths.len());
    for path in manifest_paths {
        match read_manifest(&path) {
            Ok(manifest) => manifests.push(manifest),
            Err(BackupError::Io(error)) => {
                tracing::warn!(
                    path = %path.display(),
                    error = %error,
                    "skipping unreadable manifest file"
                );
            }
            Err(error) => return Err(error),
        }
    }

    Ok(manifests)
}

/// Computes a lowercase `SHA-256(file)` hex digest using a fixed-size buffer.
///
/// # Errors
///
/// Returns [`BackupError::Io`] when opening or reading the file fails.
pub fn sha256_file_hex(path: &Path) -> BackupResult<String> {
    let mut file = fs::File::open(path)?;
    let mut hasher = Sha256::new();
    let mut buffer = vec![0_u8; HASH_BUFFER_BYTES];

    loop {
        let bytes_read = file.read(&mut buffer)?;
        if bytes_read == 0 {
            break;
        }
        hasher.update(&buffer[..bytes_read]);
    }

    Ok(HEXLOWER.encode(&hasher.finalize()))
}

fn write_manifest_temp_file(path: &Path, manifest: &BackupManifest) -> BackupResult<()> {
    let json =
        serde_json::to_vec_pretty(manifest).map_err(|_error| BackupError::InvalidManifest)?;
    let mut temp_file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?;

    temp_file.write_all(&json)?;
    temp_file.write_all(b"\n")?;
    temp_file.sync_all()?;

    Ok(())
}

fn temp_manifest_path(path: &Path) -> PathBuf {
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("manifest");
    let unique_suffix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |duration| duration.as_nanos());

    path.with_file_name(format!(
        ".{file_name}.tmp-{}-{unique_suffix}",
        std::process::id()
    ))
}

fn sync_directory(path: &Path) -> BackupResult<()> {
    #[cfg(unix)]
    {
        fs::File::open(path)?.sync_all()?;
    }
    #[cfg(not(unix))]
    {
        let _ = path;
    }

    Ok(())
}

fn is_manifest_path(path: &Path) -> bool {
    path.file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| name.ends_with(".manifest.json"))
}
